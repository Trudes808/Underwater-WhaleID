"""Collect results/*.json into tables.md (numbers only; the prose is written by hand in tables.md's head).

    .venv/bin/python experiments/04b_patch_segmentation/write_tables.py
Prints the generated part of tables.md (everything after "# Tables (generated by write_tables.py)").
"""
from __future__ import annotations

import json

import numpy as np

import common as C
from uwid import patchseg as ps

ps_classes = ps.CLASSES

R = C.HERE / "results"
CL7 = ["water", "whale", "back", "bubbles", "surface", "air"]


def f(x, nd=2):
    return "-" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def miou(iou, classes=CL7):
    v = [iou[c] for c in classes if iou.get(c) is not None]
    return float(np.mean(v)) if v else None


def seg_row(name, s):
    i = s["iou_band"]; g = s["whale_recall_by_grade"]; c = s["confusions"]
    return (f"| {name} | {s['frames']} | " + " | ".join(f(i.get(k)) for k in CL7 + ["seafloor"]) + f" | {f(miou(i))} | "
            + " | ".join(f"{f(g[k]['pixel_recall'])} ({g[k]['found_25pct']}/{g[k]['instances']})" if k in g else "-"
                         for k in ["clear", "hazy", "faint"]) + " | "
            + " | ".join(f(c[k], 3) for k in ["back_as_whale", "whale_as_back", "bubbles_as_whale", "surface_as_whale",
                                              "faint_whale_as_water", "water_as_whale"]) + " |")


SEG_HEAD = ("| run | frames | water | whale | back | bubbles | surface | air | seafloor | mIoU (6) | whale recall clear "
            "(found/n) | hazy | faint | back->whale | whale->back | bubbles->whale | surface->whale | faint->water | "
            "water->whale |\n|" + "---|" * 19)


def main():
    out = []
    p = R / "cv_compare.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Within the dev clip: input size and head (leave one time block out, single frames)", "",
                "IoU with a 12 px band around region borders ignored. Recall = share of the whale's pixels called "
                "whale; found = instances with >= 25 % of pixels called whale.", "", SEG_HEAD]
        out += [seg_row(k, v) for k, v in d.items()]
        out += ["", "Strict IoU (no border band), same runs:", "", "| run | " + " | ".join(CL7) + " |", "|" + "---|" * 7]
        out += [f"| {k} | " + " | ".join(f(v['iou'].get(c)) for c in CL7) + " |" for k, v in d.items()]
        out.append("")
    p = R / "cv_curve_w1280_h0.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Within the dev clip: learning curve (w1280 linear; training = a contiguous block of n mask frames "
                "of the training pool, 3 starting points; held-out block as above)", "",
                "| n frames | mIoU (6) | whale IoU | back IoU | bubbles IoU | surface IoU | whale recall hazy | faint |",
                "|---|---|---|---|---|---|---|---|"]
        for n, runs in d.items():
            vals = lambda fn: " / ".join(f(fn(r)) for r in runs)  # noqa: E731
            out.append(f"| {n} | {vals(lambda r: miou(r['iou_band']))} | {vals(lambda r: r['iou_band']['whale'])} | "
                       f"{vals(lambda r: r['iou_band']['back'])} | {vals(lambda r: r['iou_band']['bubbles'])} | "
                       f"{vals(lambda r: r['iou_band']['surface'])} | "
                       f"{vals(lambda r: r['whale_recall_by_grade']['hazy']['pixel_recall'])} | "
                       f"{vals(lambda r: r['whale_recall_by_grade']['faint']['pixel_recall'])} |")
        out.append("")
    p = R / "dev_windows_w1280_h0.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Within the dev clip: single frame against the 1 s window (held-out fold classifiers)", "", SEG_HEAD,
                seg_row("mask frame alone", d["masks_single"]), seg_row("mean of 7 frames (-15..+15)", d["masks_window7"]),
                "", "Whale presence (score = largest whale region in patches; whale = a clear whale on a labelled "
                "frame, free = no clear and no faint whale; faint-only units left out):", "",
                "| unit / rule | AUC | whale units | whale-free units | faint-only | threshold at FA <= 10 % | found | false alarms |",
                "|---|---|---|---|---|---|---|---|"]
        for k, v in d["presence"].items():
            o = v["op_far10"]
            out.append(f"| {k} | {f(v['auc'], 3)} | {v['n_whale']} | {v['n_free']} | {v['n_faint_only']} | {f(o['threshold'], 0)} | "
                       f"{int(o['tp'])}/{v['n_whale']} | {int(o['fp'])}/{v['n_free']} |")
        out.append("")
    p = R / "unknown_calib.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Unknown threshold (dev clip, held-out blocks)", "",
                f"Cosine distance to the nearest training patch: median {f(d['median'], 3)}, 95th pct {f(d['thr_p95'], 3)}, "
                f"99th pct {f(d['thr_p99'], 3)} (used), 99.5th {f(d['thr_p995'], 3)}; {d['n_patches']} patches.", "",
                "| class | median distance | share > p99 |", "|---|---|---|"]
        out += [f"| {k} | {f(v, 3)} | {f(d['per_class_share_over_p99'][k], 3)} |" for k, v in d["per_class_median"].items()]
        out.append("")
    for tag, title in [("", "classifier fitted on the 31 dev frames only"),
                       ("_lomo", "FITTED ON THE TEST DEPLOYMENT: leave one recording out, dev 31 + the mask frames of the "
                                 "other 2025-02-03 recordings (9-13 frames)")]:
        p = R / f"test_w1280_h0{tag}.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        out += [f"## Test recordings pooled (7 recordings, 840 labelled frames; {title})", "",
                "Whale presence, one labelled frame per window (thresholds in patches of 24 x 24 px; 'dev thr' = "
                "chosen on the dev clip at false alarms <= 10 %; the sweep is a fixed grid, not tuned):", "",
                "| unit / rule | AUC | whale | free | at dev thr: found | false alarms | thr | sweep 4: found / FA | 8 | 16 | 32 | 64 |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for k, v in d.get("pooled_presence", {}).items():
            a = v["at_dev_thr"]; sw = v["sweep"]
            out.append(f"| {k} | {f(v['auc'], 3)} | {v['n_whale']} | {v['n_free']} | {a['hits']}/{a['n_pos']} | "
                       f"{a['false_alarms']}/{a['n_neg']} | {f(a['threshold'], 0)} | "
                       + " | ".join(f"{sw[t]['hits']} / {sw[t]['false_alarms']}" for t in ["4", "8", "16", "32", "64"]) + " |")
        pm = d.get("pooled_masks", {})
        if pm:
            out += ["", f"Test mask frames pooled ({pm['single']['frames']} frames):", "", SEG_HEAD]
            out += [seg_row(k, v) for k, v in pm.items()]
            out += ["", "Rows = truth, columns = prediction (share of the truth class's pixels), single frame:", "",
                    "| truth | pixels | " + " | ".join(ps_classes + ["unknown"]) + " |", "|" + "---|" * (len(ps_classes) + 3)]
            for key in ["single", "single_unknown"]:
                if key not in pm:
                    continue
                cf = np.array(pm[key]["conf"])
                for c in range(cf.shape[0]):
                    n = cf[c].sum()
                    if n:
                        out.append(f"| {ps_classes[c]} ({key}) | {n} | " + " | ".join(f(x / n, 3) for x in cf[c]) + " |")
        out.append("")
    p = R / "test_w1280_h0.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Across deployments: 2025-02-03 recordings (classifier fitted on all 31 dev frames, thresholds from "
                "the dev clip)", ""]
        out += ["| recording | unit / rule | AUC | whale | free | faint-only | found at dev threshold | false alarms at dev threshold | threshold |",
                "|---|---|---|---|---|---|---|---|---|"]
        for stem, r in d["videos"].items():
            for k, v in r["presence"].items():
                af = v.get("at_fixed", {})
                out.append(f"| {stem[-5:]} | {k} | {f(v['auc'], 3)} | {v['n_whale']} | {v['n_free']} | {v['n_faint_only']} | "
                           f"{af.get('hits', '-')}/{af.get('n_pos', '-')} | {af.get('false_alarms', '-')}/{af.get('n_neg', '-')} | {f(af.get('threshold'), 0)} |")
        out += ["", "Back, fish, mean class shares on underwater labelled frames:", "",
                "| recording | frames with back | mean back share (with / without back) | AUC back share | fish frames with a fish patch | "
                "no-fish frames with a fish patch | mean shares water / whale / back / bubbles / surface / air |",
                "|---|---|---|---|---|---|---|"]
        for stem, r in d["videos"].items():
            b, fi, sh = r["back"], r["fish"], r["shares_underwater_mean"]
            out.append(f"| {stem[-5:]} | {b['frames_with_back']} | {f(b['mean_back_share_with'], 3)} / {f(b['mean_back_share_without'], 3)} | "
                       f"{f(b['auc_back_share'], 3)} | {fi['fish_frames_with_fish_patch']}/{fi['fish_frames']} | "
                       f"{fi['nofish_frames_with_fish_patch']}/{fi['nofish_frames']} | "
                       + " / ".join(f(sh[c], 3) for c in CL7) + " |")
        rows = [(s, k, v) for s, r in d["videos"].items() for k, v in r.get("m2f_seafloor_called", {}).items()]
        if rows:
            out += ["", "What the classifier calls the pixels Mask2Former calls sand / rock / earth / floor / mountain:", "",
                    "| recording | frame label seafloor | frames | frames with M2F seafloor | water | whale | back | bubbles | surface | air | unknown |",
                    "|---|---|---|---|---|---|---|---|---|---|---|"]
            out += [f"| {s[-5:]} | {k} | {v['frames']} | {v['frames_with_m2f_seafloor']} | " + " | ".join(f(v[c], 3) for c in CL7)
                    + f" | {f(v.get('unknown'), 3)} |" for s, k, v in rows]
        mrows = [(s, r["masks"]) for s, r in d["videos"].items() if "masks" in r]
        if mrows:
            out += ["", "Test mask frames (WP3 AI by-eye masks):", "", SEG_HEAD]
            for s, m in mrows:
                out.append(seg_row(f"{s[-5:]} single", m["single"]))
                out.append(seg_row(f"{s[-5:]} window mean", m["window"]))
                if m.get("single_unknown"):
                    out.append(seg_row(f"{s[-5:]} single + unknown", m["single_unknown"]))
            out += ["", "Seafloor pixels in the test masks, predicted as (single frame):", "",
                    "| recording | seafloor px | water | whale | back | fish | bubbles | surface | air | seafloor | unknown |",
                    "|---|---|---|---|---|---|---|---|---|---|---|"]
            for s, m in mrows:
                for key in ["single", "single_unknown"]:
                    if not m.get(key):
                        continue
                    row = np.array(m[key]["conf"][7]); n = row.sum()
                    if n:
                        out.append(f"| {s[-5:]} {key} | {n} | " + " | ".join(f(x / n, 3) for x in row) + " |")
        out.append("")
    for name, title in [("test_curve.json", "Learning curve on the test masks (dev frames only; contiguous block of n dev mask frames)"),
                        ("test_adapt.json", "FITTED ON THE TEST DEPLOYMENT: dev 31 + k mask frames of one recording, scored on the other recordings' mask frames")]:
        p = R / name
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        out += [f"## {title}", "", SEG_HEAD]
        if name == "test_curve.json":
            for n, runs in d["runs"].items():
                for j, r in enumerate(runs):
                    out.append(seg_row(f"{n} dev frames (start {j})", r))
        else:
            for r in d["runs"]:
                out.append(seg_row(f"+{r['k']} of {r['source'][-5:]} -> {','.join(s[-5:] for s in r['scored_on'])}", r))
        out.append("")
    p = R / "cost.json"
    if p.exists():
        d = json.loads(p.read_text())
        out += ["## Cost (first 120 s of recording 00005; RTX 4000 Ada shared)", "",
                "| input | stride | frames decoded | frames classified | wall s | decode s | GPU part s | video s | GPU h per video h | peak GPU GB |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for k, t in d.items():
            ext, st = k.split("_stride")
            out.append(f"| {ext} | {st} | {t['frames_decoded']} | {t['frames_classified']} | {f(t['wall_s'], 1)} | {f(t['decode_s'], 1)} | "
                       f"{f(t['gpu_s'], 1)} | {f(t['video_s'], 1)} | {f(t['gpu_h_per_video_h'], 3)} | {f(t['peak_gpu_gb'], 2)} |")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
